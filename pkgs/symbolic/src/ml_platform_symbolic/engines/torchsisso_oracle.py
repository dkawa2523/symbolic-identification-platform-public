"""Pinned native descriptor arithmetic without batch-dependent column removal.

Only validation uses this isolated copy. Native search/feature screening is not
modified. Each selected expression is replayed one operator at a time by the
actual upstream methods, retaining their NaN/Inf rather than dropping columns.
"""

import hashlib
from functools import lru_cache
from importlib import import_module
from pathlib import Path
from types import SimpleNamespace

import numpy as np

from ..expressions import parse_expression


@lru_cache(maxsize=1)
def native_methods():
    module = import_module("TorchSisso.FeatureSpaceConstruction")
    data = Path(module.__file__).read_bytes()
    if hashlib.sha256(data).hexdigest() != "26b33ff4eb469f8e3823ce8062db4ec0906680119fa83bfd3de02f89b238d7c9":
        raise ValueError("Descriptor oracle requires reviewed TorchSisso 0.1.8 feature source")
    source = data.decode("utf-8")
    anchor = "nan_or_inf_columns = nan_columns | inf_columns"
    if source.count(anchor) != 2:
        raise ValueError("Native descriptor filtering context differs")
    # Preserve native operator evaluation exactly; suppress only subsequent
    # whole-column deletion in this private validation-only module namespace.
    source = source.replace(anchor, "nan_or_inf_columns = torch.zeros_like(nan_columns)")
    namespace = {"__name__": "TorchSisso._descriptor_oracle", "__package__": "TorchSisso"}
    exec(compile(source, str(module.__file__) + "[validation-only]", "exec"), namespace)
    return namespace["feature_space_construction"]


def descriptor_values(names, X, variables, *, device="cpu"):
    """Evaluate fixed selected descriptors, including invalid rows and batches."""
    import torch

    constructor = native_methods()
    values = torch.as_tensor(np.asarray(X), dtype=torch.float64, device=device)
    columns = {v["id"]: i for i, v in enumerate(variables)}
    unary = {"exp": "exp", "log": "ln", "sin": "sin", "cos": "cos", "tanh": "tanh", "sinh": "sinh", "cosh": "cosh"}
    binary = {"add": "+", "sub": "-", "mul": "*", "div": "/"}

    def visit(node):
        if "var" in node:
            return values[:, columns[node["var"]]]
        if "const" in node:
            return torch.full((len(X),), float(node["const"]), dtype=values.dtype, device=device)
        op, children = node["op"], node["args"]
        if op == "pow_int":
            exponent = children[1].get("const")
            if exponent not in (2, 3, 4):
                raise ValueError("Descriptor exponent was not generated by this native adapter")
            operator, args = f"pow({int(exponent)})", [visit(children[0])]
        elif op in unary:
            operator, args = unary[op], [visit(children[0])]
        elif op in binary:
            operator, args = binary[op], [visit(child) for child in children]
        else:
            raise ValueError(f"No reviewed native descriptor oracle for {op}")
        empty = torch.empty((len(X), 0), device=device)
        state = SimpleNamespace(
            df=np.empty((len(X), len(args))),
            df_feature_values=torch.stack(args, dim=1),
            columns=[f"a{i}" for i in range(len(args))],
            device=torch.device(device),
            operators=[operator],
            no_of_operators=2,
            custom_binary_functions=None,
            custom_unary_functions=None,
            feature_values_binary=empty,
            feature_names_binary=[],
            feature_values_unary=empty,
            feature_names_unary=[],
        )
        # i+1 == no_of_operators disables the native data-dependent duplicate
        # elimination. One unary or ordered pair is evaluated, not re-searched.
        method = constructor.single_variable if len(args) == 1 else constructor.combinations
        result, labels = method(state, [operator], 1)
        expected = 1 if len(args) == 1 or op != "div" else 2
        if result.shape != (len(X), expected) or len(labels) != expected:
            raise ValueError("Native descriptor oracle returned unexpected columns")
        return result[:, 0]  # Native division first column is a0/a1, second a1/a0.

    return torch.stack(
        [visit(parse_expression(name.replace("ln(", "log("), variables, trainable=False)["ast"]) for name in names],
        dim=1,
    )
